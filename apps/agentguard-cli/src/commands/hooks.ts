/**
 * `okgate hooks install|uninstall|status [--project|--user] [--client claude|codex|gemini]`
 *
 * Install writes the coding agent's pre-execution hook entry (Claude Code `PreToolUse`, Codex
 * `PreToolUse`, Gemini CLI `BeforeTool`) pointing at `okgate hook pre-tool-use`, and makes
 * sure the policy has a `hooks:` block in dry-run. Uninstall removes only okgate's entries.
 */
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import {
  LEGACY_POLICY_FILE,
  LEGACY_STATE_DIR,
  POLICY_FILE,
  STATE_DIR,
  type HookClient,
} from "@agentwares/agentguard-core";
import { findPolicyFile } from "@agentwares/agentguard-core/node";
import { flagBool, flagList, flagNumber, flagString, type ParsedArgs } from "../args.js";
import { homeFrom, type Io } from "../context.js";
import {
  CLIENT_ALIASES,
  hookTarget,
  installHook,
  installedHandlers,
  uninstallHook,
  type InstallScope,
} from "../hooks/clients.js";
import { npxCommand } from "../install.js";
import { version } from "../version.js";

/** `~/.okgate/okgate.yaml`, or the `~/.agentguard/agentguard.yaml` an earlier install wrote. */
export function userPolicyPath(home: string): string {
  const next = join(home, STATE_DIR, POLICY_FILE);
  const legacy = join(home, LEGACY_STATE_DIR, LEGACY_POLICY_FILE);
  return !existsSync(next) && existsSync(legacy) ? legacy : next;
}

/** The commented `hooks:` block: the file people read, so every knob explains itself. */
export const HOOKS_POLICY_BLOCK = `
# Hook mode: your coding agent's own shell commands and file edits (Claude Code, Codex, Gemini CLI),
# checked before they run. \`okgate hooks install\` wired it; \`okgate report\` shows the decisions.
hooks:
  # dry-run: every decision is logged and nothing is blocked. Read \`okgate report\`, then set
  # enforce. The kill switch (\`okgate kill\`) stops guarded calls in both modes.
  mode: dry-run
  # Irreversible commands run only on a turn a person typed: after the session's previous
  # irreversible command, recent, and naming the action ("push it", or "yes" to "shall I push?").
  # Text the model writes, tool output and injected messages never count. Otherwise the agent
  # gets APPROVAL_REQUIRED and an id; \`okgate approve <id>\` lets that exact command run once.
  # Built in: git-push, merge, tag-delete, rm-outside-workspace, publish, send, guard-config.
  irreversible:
    builtins: true
    window_s: 1800          # the authorizing turn is at most 30 minutes old
    require_mention: true   # ...and names the action
    require_origin: false   # true: only entries Claude Code labels as typed by a person
    mentions: {}            # extra words per class, e.g. { git-push: [deploy] }
    rules: []
    #  - name: deploy
    #    shell: ["vercel --prod*", "fly deploy*"]
    #    mentions: [deploy]
  shell:
    deny: []                # e.g. ["terraform destroy*", "curl * | sh"]
    approval: []            # e.g. ["kubectl delete *"]
  paths:
    deny: []                # e.g. [".env", "*.pem"]
    approval: []            # e.g. ["**/migrations/**"]
`;

/** A policy for a project that has no okgate.yaml yet: hooks only, no MCP upstreams. */
export function renderHooksStarterPolicy(generatedAt = new Date()): string {
  return `# okgate.yaml — generated by \`okgate hooks install\` on ${generatedAt.toISOString().slice(0, 10)}
# Docs: https://github.com/agentwares/agentguard/tree/main/apps/agentguard-cli#hook-mode-a-coding-agents-own-commands
version: 1

# MCP proxy mode (okgate init) reads upstreams; hook mode needs none.
mode: dry-run
upstreams: []
${HOOKS_POLICY_BLOCK}
# Kill switch: \`okgate kill\` creates this file; every guarded call is refused until
# \`okgate resume\`. OKGATE_KILL=1 (or AGENTGUARD_KILL=1) in the environment does the same.
kill:
  file: .okgate/KILL

# Hash-chained JSONL of every decision; \`okgate verify\` proves it was not edited.
audit:
  path: .okgate/audit.jsonl
  redact: true
`;
}

function quoteArg(arg: string): string {
  return /^[A-Za-z0-9_@%+=:,./-]+$/.test(arg) ? arg : JSON.stringify(arg);
}

function clientsFrom(args: ParsedArgs): HookClient[] {
  const names = flagList(args, "client");
  if (names.length === 0) return ["claude-code"];
  if (names.includes("all")) return ["claude-code", "codex", "gemini-cli"];
  return names.map((n) => {
    const c = CLIENT_ALIASES[n.trim()];
    if (!c) throw new Error(`unknown --client "${n}" (claude, codex, gemini or all)`);
    return c;
  });
}

function hasTopLevelHooks(yamlText: string): boolean {
  return /^hooks\s*:/m.test(yamlText);
}

export async function hooksCommand(args: ParsedArgs, io: Io): Promise<number> {
  const sub = args.positionals[0] ?? "status";
  const scope: InstallScope = flagBool(args, "user") ? "user" : "project";
  const home = homeFrom(io);
  const where = { cwd: io.cwd, home };
  const rel = (p: string): string => {
    const r = relative(io.cwd, p);
    return r.startsWith("..") ? p : r || ".";
  };
  const clients = clientsFrom(args);
  const named = flagString(args, "config");
  const policyPath =
    named !== undefined
      ? resolve(io.cwd, named)
      : scope === "user"
        ? userPolicyPath(home)
        : findPolicyFile(io.cwd);
  const base = flagString(args, "command") ?? npxCommand(version());
  const commandFor = (client: HookClient): string => {
    let cmd = `${base} hook pre-tool-use --client ${client === "claude-code" ? "claude" : client === "gemini-cli" ? "gemini" : "codex"}`;
    if (flagString(args, "config")) cmd += ` --config ${quoteArg(policyPath)}`;
    else if (scope === "user") cmd += ` --fallback-config ${quoteArg(policyPath)}`;
    return cmd;
  };
  const timeoutS = Math.max(30, flagNumber(args, "timeout") ?? 30);

  if (sub === "install") {
    // the policy first: a hook with no policy to read guards nothing
    if (!existsSync(policyPath)) {
      mkdirSync(dirname(policyPath), { recursive: true });
      writeFileSync(policyPath, renderHooksStarterPolicy());
      io.out(`wrote   ${rel(policyPath)} (hooks.mode: dry-run)`);
    } else if (!hasTopLevelHooks(readFileSync(policyPath, "utf8"))) {
      appendFileSync(policyPath, HOOKS_POLICY_BLOCK);
      io.out(`added   a hooks: block to ${rel(policyPath)} (hooks.mode: dry-run)`);
    } else io.out(`kept    ${rel(policyPath)} (it already has a hooks: block)`);

    for (const client of clients) {
      const target = hookTarget(client, scope, where, commandFor(client), timeoutS);
      const { status, backup } = installHook(target);
      const verb =
        status === "unchanged" ? "kept   " : status === "updated" ? "updated" : "added  ";
      io.out(
        `${verb} ${target.label} ${target.event} hook in ${rel(target.settingsPath)}${backup ? ` (backup: ${rel(backup)})` : ""}`,
      );
      if (target.note) io.out(`        ${target.note}`);
    }

    if (scope === "project" && existsSync(join(io.cwd, ".git"))) {
      const gitignore = join(io.cwd, ".gitignore");
      const text = existsSync(gitignore) ? readFileSync(gitignore, "utf8") : "";
      if (!/^\/?\.okgate\/?$/m.test(text)) {
        appendFileSync(gitignore, `${text && !text.endsWith("\n") ? "\n" : ""}.okgate/\n`);
        io.out(`added   .okgate/ to .gitignore (approvals, counters and the audit log stay local)`);
      }
    }

    io.out("");
    io.out("Next:");
    io.out("  1. start a new session of your coding agent (hooks are read at start)");
    io.out("  2. work as usual — hooks.mode is dry-run: decisions are logged, nothing is blocked");
    io.out("  3. okgate report    # what enforce mode would have stopped, and why");
    io.out(`  4. set \`hooks.mode: enforce\` in ${rel(policyPath)} when it looks right`);
    io.out("  undo: okgate hooks uninstall" + (scope === "user" ? " --user" : ""));
    return 0;
  }

  if (sub === "uninstall") {
    let total = 0;
    for (const client of flagString(args, "client")
      ? clients
      : (["claude-code", "codex", "gemini-cli"] as HookClient[])) {
      const target = hookTarget(client, scope, where, commandFor(client), timeoutS);
      const removed = uninstallHook(target);
      total += removed;
      if (removed) io.out(`removed ${target.label} hook from ${rel(target.settingsPath)}`);
    }
    if (total === 0) io.out(`no okgate hooks in ${scope}-level settings`);
    else
      io.out(
        `kept    ${rel(policyPath)} and its state directory (${STATE_DIR}/ or ${LEGACY_STATE_DIR}/); delete them yourself if you want them gone`,
      );
    return 0;
  }

  if (sub === "status") {
    for (const s of ["project", "user"] as InstallScope[]) {
      for (const client of ["claude-code", "codex", "gemini-cli"] as HookClient[]) {
        const target = hookTarget(client, s, where, "", timeoutS);
        let handlers: Record<string, unknown>[];
        try {
          handlers = installedHandlers(target);
        } catch (err) {
          io.out(
            `${s.padEnd(7)} ${target.label.padEnd(11)} unreadable: ${err instanceof Error ? err.message : String(err)}`,
          );
          continue;
        }
        io.out(
          `${s.padEnd(7)} ${target.label.padEnd(11)} ${handlers.length ? `installed: ${String(handlers[0]!.command)}` : "—"}  (${rel(target.settingsPath)})`,
        );
      }
    }
    return 0;
  }

  io.err(
    "usage: okgate hooks install|uninstall|status [--project|--user] [--client claude|codex|gemini|all] [--command cmd] [--config path]",
  );
  return 1;
}
